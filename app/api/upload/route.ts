import { NextResponse } from "next/server";
import { z } from "zod";
import { badRequest, errorMessage } from "@/lib/http";
import { ALLOWED_MIME_TYPES, MAX_UPLOAD_BYTES } from "@/lib/pipeline";
import { getServerSupabase } from "@/lib/supabase-server";

// No route segment config except where noted: cacheComponents rejects `dynamic`, `revalidate`, etc.

const BodySchema = z.object({
  uploadId: z.string().uuid(), // generated by the browser; makes retries idempotent
  filename: z.string().trim().min(1).max(200),
  mimeType: z.enum(ALLOWED_MIME_TYPES),
  sizeBytes: z.number().int().positive().max(MAX_UPLOAD_BYTES),
  kind: z.enum(["photo", "scan", "pano"]).optional(),
  title: z.string().trim().max(200).optional(),
  notes: z.string().trim().max(2000).optional(),
});

function safeFilename(name: string): string {
  const cleaned = name
    .normalize("NFKD")
    .replace(/[^a-zA-Z0-9._-]+/g, "_")
    .replace(/^[._]+/, "")
    .slice(-100);
  return cleaned.length > 0 ? cleaned : "upload";
}

export async function POST(req: Request) {
  const raw: unknown = await req.json().catch(() => null);
  if (raw === null) {
    return NextResponse.json(
      { ok: false, error: "Body must be valid JSON" },
      { status: 400 },
    );
  }
  const parsed = BodySchema.safeParse(raw);
  if (!parsed.success) return badRequest(parsed.error);
  const body = parsed.data;

  const bucket = process.env.SUPABASE_STORAGE_BUCKET;
  if (!bucket) {
    return NextResponse.json(
      { ok: false, error: "SUPABASE_STORAGE_BUCKET is not set on the server" },
      { status: 500 },
    );
  }

  try {
    const db = getServerSupabase();
    const uploadId = body.uploadId.toLowerCase();
    const kind =
      body.mimeType === "application/pdf" ? "scan" : (body.kind ?? "photo");
    const path = `uploads/${uploadId}/${safeFilename(body.filename)}`;

    // 1. Asset row. Same uploadId => same row (do nothing on conflict).
    const { error: assetErr } = await db.from("assets").upsert(
      {
        id: uploadId,
        kind,
        storage_bucket: bucket,
        storage_path: path,
        original_filename: body.filename,
        mime_type: body.mimeType,
        size_bytes: body.sizeBytes,
        title: body.title || null,
        notes: body.notes || null,
      },
      { onConflict: "id", ignoreDuplicates: true },
    );
    if (assetErr)
      throw new Error(`Could not create asset: ${assetErr.message}`);

    const { data: asset, error: readErr } = await db
      .from("assets")
      .select("id, storage_bucket, storage_path")
      .eq("id", uploadId)
      .single();
    if (readErr || !asset)
      throw new Error(`Could not read asset back: ${readErr?.message}`);
    const a = asset as {
      id: string;
      storage_bucket: string;
      storage_path: string;
    };

    // 2. Job row: one per asset (unique(asset_id)).
    const { error: jobErr } = await db
      .from("jobs")
      .upsert(
        { asset_id: a.id },
        { onConflict: "asset_id", ignoreDuplicates: true },
      );
    if (jobErr) throw new Error(`Could not create job: ${jobErr.message}`);

    const { data: job, error: jobReadErr } = await db
      .from("jobs")
      .select("id")
      .eq("asset_id", a.id)
      .single();
    if (jobReadErr || !job)
      throw new Error(`Could not read job back: ${jobReadErr?.message}`);

    // 3. Signed upload URL: the browser uploads straight to Storage with this token.
    const { data: signed, error: signErr } = await db.storage
      .from(a.storage_bucket)
      .createSignedUploadUrl(a.storage_path);
    if (signErr || !signed) {
      throw new Error(
        `Could not create signed upload URL: ${signErr?.message ?? "no data"}`,
      );
    }

    return NextResponse.json({
      ok: true,
      jobId: (job as { id: string }).id,
      assetId: a.id,
      bucket: a.storage_bucket,
      path: a.storage_path,
      token: signed.token,
      signedUrl: signed.signedUrl,
    });
  } catch (err) {
    console.error("[api/upload]", err);
    return NextResponse.json(
      { ok: false, error: errorMessage(err) },
      { status: 500 },
    );
  }
}
